// ─── فحص جودة لغوية للرد قبل عرضه ──────────────────────────────────────────
// منقولة بتصرّف من ShahdGuard::isUsableReply (almoaser-site، قُرئت ٢١
// أغسطس ٢٠٢٦، مراجعة حرفية بطلب المالك). agentModes.ts يطلب من النموذج
// "لا تُدخلي أي حرف من لغة ثالثة" كتعليمة نصّية بحتة — بلا حارس فعلي
// يتحقق من الالتزام، بنفس الفخ الذي وثّقته شهد قبل هذا الحارس ("المستند
// الذي 记录的 البيع" تسريب حقيقي من نموذج متعدد اللغات).
//
// لا حكم على المحتوى، فقط على ما يدلّ على عطل لغوي.

/** صينية/يابانية/كورية + هندية/بنغالية/لاوية/سيريلية/أرمنية */
const FOREIGN_SCRIPT = /[一-鿿぀-ヿ가-힯ऀ-ॿঀ-৿฀-໿Ѐ-ӿ԰-֏]/u;

/** حرف لاتيني ملتصق بعربي بلا مسافة — أثر نموذج خلط رموزه، لا كتابة بشرية */
const LATIN_STUCK_TO_ARABIC = /[؀-ۿ][a-zA-Z]{2,}|[a-zA-Z]{2,}[؀-ۿ]/u;

/**
 * هل الرد صالح للعرض؟ يُستدعى بعد verifyReply — الاثنان مستقلان: هذا
 * يفحص جودة اللغة، ذاك يفحص صدق الادّعاء.
 */
export function isUsableReply(reply: string): boolean {
  const t = reply.trim();
  if (t.length < 2) return false;
  if (FOREIGN_SCRIPT.test(t)) return false;
  if (LATIN_STUCK_TO_ARABIC.test(t)) return false;
  return true;
}

export const UNUSABLE_REPLY_FALLBACK =
  "حصل خلل في صياغة الردّ — جرّب تسأل بصيغة تانية.";
